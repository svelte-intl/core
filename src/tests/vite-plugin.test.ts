import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { build, parseAst } from 'vite';
import { createServer, type Server } from 'node:http';
import {
	mkdtempSync,
	mkdirSync,
	readFileSync,
	rmSync,
	writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { findSources, i18n, renderTypes } from '../lib/vite-plugin-i18n.ts';

describe('findSources', () => {
	it('finds import() paths and fetch() URLs in createI18n and extend calls', () => {
		const program = parseAst(`
			createI18n({
				locales: ['en', 'nl'],
				dictionaries: {
					en: async () => (await import('./locales/en.json')).default,
					nl: () => fetch(\`https://cdn.example.com/nl.json\`).then((r) => r.json())
				}
			});
			i18n.extend({ en: () => import('./page/en.json') });
			other({ dictionaries: { en: () => import('./ignored.json') } });
		`);

		expect(findSources(program as never)).toEqual({
			imports: ['./locales/en.json', './page/en.json'],
			urls: ['https://cdn.example.com/nl.json']
		});
	});
});

describe('renderTypes', () => {
	it('escapes keys safely and sorts them', () => {
		const output = renderTypes([
			"it's",
			'a\\b',
			'line\nbreak',
			'Hello, {name}!',
			"it's"
		]);

		expect(output).toContain('\t"it\'s": string;');
		expect(output).toContain('\t"a\\\\b": string;');
		expect(output).toContain('\t"line\\nbreak": string;');
		expect(output.match(/it's/g)).toHaveLength(1);
		expect(output.indexOf('Hello')).toBeLessThan(output.indexOf('a\\\\b'));
	});
});

describe('i18n() plugin in a Vite build', () => {
	let root: string;
	let server: Server;
	let port: number;

	beforeAll(async () => {
		server = createServer((req, res) => {
			res.setHeader('content-type', 'application/json');
			if (req.url === '/nl.json')
				res.end(JSON.stringify({ 'From the API': 'Van de API' }));
			else if (req.url === '/nested.json')
				res.end(JSON.stringify({ a: { b: 'c' } }));
			else {
				res.statusCode = 404;
				res.end('{}');
			}
		});
		await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
		port = (server.address() as { port: number }).port;

		root = mkdtempSync(join(tmpdir(), 'svelte-i18n-plugin-'));
		mkdirSync(join(root, 'src/locales'), { recursive: true });
		writeFileSync(
			join(root, 'src/locales/en.json'),
			JSON.stringify({ Hello: 'Hello', "it's": 'x' })
		);
		writeFileSync(
			join(root, 'src/locales/extra.json'),
			JSON.stringify({ Extra: 'Extra' })
		);
		writeFileSync(
			join(root, 'src/main.ts'),
			`
			declare const createI18n: (o: unknown) => { extend(o: unknown): void };
			const i18n = createI18n({
				locales: ['en', 'nl'],
				dictionaries: {
					en: async () => (await import('./locales/en.json')).default,
					nl: async () => (await fetch('http://127.0.0.1:${port}/nl.json')).json()
				}
			});
			i18n.extend({
				en: async () => (await import('./locales/extra.json')).default,
				nl: async () => (await fetch('http://127.0.0.1:${port}/nested.json')).json()
			});
			export default i18n;
			`
		);
	});

	afterAll(() => {
		server.close();
		rmSync(root, { recursive: true, force: true });
	});

	it('writes every key from imports, fetches and extend calls', async () => {
		await build({
			root,
			logLevel: 'silent',
			plugins: [i18n()],
			build: {
				write: false,
				lib: {
					entry: join(root, 'src/main.ts'),
					formats: ['es'],
					fileName: 'main'
				}
			}
		});

		const types = readFileSync(join(root, 'src/lib/i18n-types.d.ts'), 'utf-8');
		expect(types).toBe(
			[
				'// Generated by @svelte-i18n/core/vite. Do not edit.',
				'export type I18nDictionary = {',
				'\t"Extra": string;',
				'\t"From the API": string;',
				'\t"Hello": string;',
				'\t"it\'s": string;',
				'};',
				''
			].join('\n')
		);
	});

	it('respects a custom output path', async () => {
		await build({
			root,
			logLevel: 'silent',
			plugins: [i18n({ output: 'types/custom.d.ts', fetch: false })],
			build: {
				write: false,
				lib: {
					entry: join(root, 'src/main.ts'),
					formats: ['es'],
					fileName: 'main'
				}
			}
		});

		const types = readFileSync(join(root, 'types/custom.d.ts'), 'utf-8');
		expect(types).toContain('"Hello"');
		expect(types).not.toContain('From the API');
	});
});
